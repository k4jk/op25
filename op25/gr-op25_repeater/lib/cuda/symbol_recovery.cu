#include <cstring>

// ---------------------------------------------------------------------------
// GNU Radio MMSE FIR interpolator table (verbatim from
//   /usr/include/gnuradio/filter/interpolator_taps.h, generated by
//   gen_interpolator_taps — do not edit by hand).
//
// Table: taps[NSTEPS+1][NTAPS] = taps[129][8].
// Columns are labelled -4 -3 -2 -1 0 +1 +2 +3 (offsets from output position).
//
// Calling convention: to interpolate at position mu = i0 + frac
//   (i0 = floor(mu), frac = mu - i0):
//
//   imu = round((1-frac) * NSTEPS)         ← NOTE: 1-frac, not frac
//   output = Σ_{t=0}^{7} taps[imu][t] × x[i0-3+t]
//
// Why (1-frac):  at frac=0, imu=128, tap[128][3]=1 → x[i0] (correct).
//                at frac=1, imu=0,   tap[0][4]=1   → x[i0+1] (correct).
//                Using frac directly gives x[i0+1] at frac=0 — 1 sample late.
//
// The 8 samples span x[i0-3] through x[i0+4]; break when i0+4 >= in_steps.
// ---------------------------------------------------------------------------
namespace gr_interp {
#include <gnuradio/filter/interpolator_taps.h>
}

// ---------------------------------------------------------------------------
// MMSE FIR table in GPU constant memory (129×8 floats = 4128 bytes).
// Uploaded once from gr_interp::taps in mm_alloc().
// ---------------------------------------------------------------------------
// MM_HIST defined in symbol_recovery.h (constexpr, shared with cuda_channelizer_impl.cc)
#define MM_NSTEPS 128   // must equal gr_interp::NSTEPS
#define MM_NTAPS    8   // must equal gr_interp::NTAPS

__constant__ float c_mmse_taps[MM_NSTEPS + 1][MM_NTAPS];

#define CUDA_CHECK_MM(call)                                                   \
