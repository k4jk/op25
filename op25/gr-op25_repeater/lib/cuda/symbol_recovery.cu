bool mm_alloc(ChannelizerState& state)
{
    const int C = state.config.fft_size;

    // Upload GNU Radio MMSE FIR table to GPU constant memory.
    // gr_interp::taps is float[129][8] — same layout as c_mmse_taps.
    static_assert(sizeof(gr_interp::taps) == (MM_NSTEPS + 1) * MM_NTAPS * sizeof(float),
                  "GR table size mismatch — check NSTEPS/NTAPS defines");
    CUDA_CHECK_MM(cudaMemcpyToSymbol(c_mmse_taps, gr_interp::taps,
                                     sizeof(gr_interp::taps)));

    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_mu,
                             static_cast<size_t>(C) * sizeof(float)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_fm_last,
                             static_cast<size_t>(MM_HIST * C) * sizeof(float)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_last_interp,
                             static_cast<size_t>(C) * sizeof(float)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_last_dec,
                             static_cast<size_t>(C) * sizeof(float)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_omega,
                             static_cast<size_t>(C) * sizeof(float)));

    cudaMemset(state.d_mm_mu,          0, static_cast<size_t>(C) * sizeof(float));
    cudaMemset(state.d_mm_fm_last,     0, static_cast<size_t>(MM_HIST * C) * sizeof(float));
    cudaMemset(state.d_mm_last_interp, 0, static_cast<size_t>(C) * sizeof(float));
    cudaMemset(state.d_mm_last_dec,    0, static_cast<size_t>(C) * sizeof(float));
    cudaMemset(state.d_mm_omega,       0, static_cast<size_t>(C) * sizeof(float));

    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_symbols,
                             static_cast<size_t>(MM_MAX_SYM) * C * sizeof(float)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_dibits,
                             static_cast<size_t>(MM_MAX_SYM) * C * sizeof(int8_t)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_sym_count,
                             static_cast<size_t>(C) * sizeof(int32_t)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_dc_est,
                             static_cast<size_t>(C) * sizeof(float)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_fast_ctr,
                             static_cast<size_t>(C) * sizeof(int32_t)));

    cudaMemset(state.d_mm_sym_count, 0, static_cast<size_t>(C) * sizeof(int32_t));
    cudaMemset(state.d_mm_dc_est,    0, static_cast<size_t>(C) * sizeof(float));
    cudaMemset(state.d_mm_fast_ctr,  0, static_cast<size_t>(C) * sizeof(int32_t));

    // Phase 2 state
    CUDA_CHECK_MM(cudaMalloc(&state.d_channel_mode,
                             static_cast<size_t>(C) * sizeof(int8_t)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_p2_iq_last,
                             static_cast<size_t>(MM_HIST * C) * sizeof(cufftComplex)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_p2_last_sym,
                             static_cast<size_t>(C) * sizeof(cufftComplex)));

    cudaMemset(state.d_channel_mode, 1, static_cast<size_t>(C) * sizeof(int8_t));  // default Phase1
    cudaMemset(state.d_p2_iq_last,   0, static_cast<size_t>(MM_HIST * C) * sizeof(cufftComplex));
    cudaMemset(state.d_p2_last_sym,  0, static_cast<size_t>(C) * sizeof(cufftComplex));

    // Warmup gate: 1=coast (S2 history still filling), 0=run normally
    CUDA_CHECK_MM(cudaMalloc(&state.d_mm_in_warmup,
                             static_cast<size_t>(C) * sizeof(int8_t)));
    cudaMemset(state.d_mm_in_warmup, 0, static_cast<size_t>(C) * sizeof(int8_t));

    // IQ derotation state (modes 2 and 3)
    CUDA_CHECK_MM(cudaMalloc(&state.d_iq_derot_step,
                             static_cast<size_t>(C) * sizeof(float)));
    CUDA_CHECK_MM(cudaMalloc(&state.d_iq_derot_acc,
                             static_cast<size_t>(C) * sizeof(float)));
    cudaMemset(state.d_iq_derot_step, 0, static_cast<size_t>(C) * sizeof(float));
    cudaMemset(state.d_iq_derot_acc,  0, static_cast<size_t>(C) * sizeof(float));

    // Costas loop state (mode 3 only; stays zero for modes 1/2)
    CUDA_CHECK_MM(cudaMalloc(&state.d_costas_phase,
                             static_cast<size_t>(C) * sizeof(float)));
    cudaMemset(state.d_costas_phase, 0, static_cast<size_t>(C) * sizeof(float));

    CUDA_CHECK_MM(cudaMalloc(&state.d_costas_freq,
                             static_cast<size_t>(C) * sizeof(float)));
    cudaMemset(state.d_costas_freq, 0, static_cast<size_t>(C) * sizeof(float));

    CUDA_CHECK_MM(cudaMalloc(&state.d_costas_slip_ctr,
                             static_cast<size_t>(C) * sizeof(int32_t)));
    cudaMemset(state.d_costas_slip_ctr, 0, static_cast<size_t>(C) * sizeof(int32_t));

    return true;
}

void mm_process(ChannelizerState& state, int in_steps, int debug)
{
    const int C = state.config.fft_size;

    const float sps_p1 = state.config.channel_bw_hz / 4800.0f;
    const float sps_p2 = state.config.channel_bw_hz / 6000.0f;

    constexpr int CHAN_W = 512;
    mm_recovery_kernel<<<(C + CHAN_W - 1) / CHAN_W, CHAN_W>>>(
        state.d_fm_filtered,
        state.d_s2_output,
        state.d_mm_mu,
        state.d_mm_omega,
        state.d_mm_fm_last,
        state.d_p2_iq_last,
        state.d_mm_last_interp,
        state.d_p2_last_sym,
        state.d_mm_dc_est,
        state.d_channel_mode,
        state.d_mm_in_warmup,
        state.d_mm_symbols,
        state.d_mm_dibits,
        state.d_mm_sym_count,
        state.d_mm_fast_ctr,
        state.d_iq_derot_step,
        state.d_iq_derot_acc,
        state.d_costas_phase,
        state.d_costas_freq,
        state.d_costas_slip_ctr,
        debug,
        C, in_steps, sps_p1, sps_p2);
}

